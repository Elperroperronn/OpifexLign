function InicioSesion_Registro() {
  // Nota el punto "." antes de Registrar, funciona como en CSS
  const elemento = document.querySelector(".Registrar");
  const elementoPadre = document.querySelector(".InicioSesion");

  if (elemento.style.display === "flex") {
    elemento.style.display = "none";
  } else {
    elemento.style.display = "flex"; // Cambié este a "flex" para que se muestre
  }

  elementoPadre.style.display = "none";
}

